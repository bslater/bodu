using System.Security.Cryptography;
using Bodu.Test;
using Bodu.Test.Kat;

namespace Bodu.IO.Compound;

/// <summary>
/// Validates the reader against an independent corpus of well-formed compound files, using a manifest generated by a
/// separate reference parser.
/// </summary>
[TestClass]
public class CompoundReferenceFixtureTests
{
    /// <summary>
    /// Verifies that every valid reference fixture is recognized and exposes the directory entries recorded in the
    /// manifest.
    /// </summary>
    /// <param name="kat">The reference fixture row.</param>
    [TestMethod]
    [TestCategory(TestCategories.Regression)]
    [DynamicData(nameof(CompoundReferenceManifest.ValidFixtures), typeof(CompoundReferenceManifest),
        DynamicDataDisplayName = nameof(KatDisplayName.GetDisplayName),
        DynamicDataDisplayNameDeclaringType = typeof(KatDisplayName))]
    public void Open_WhenReferenceFixtureIsValid_ShouldEnumerateExpectedEntries(CompoundReferenceFixtureKat kat)
    {
        using MemoryStream source = CompoundFixtures.OpenReference(kat.RelativePath);
        Assert.IsTrue(CompoundFile.IsCompoundFile(source));

        using CompoundFile file = CompoundFile.Open(source);
        Dictionary<string, CompoundEntryInfo> actual = Flatten(file.RootStorage);

        foreach (CompoundManifestEntry expected in kat.Entries)
        {
            Assert.IsTrue(actual.TryGetValue(expected.Path, out CompoundEntryInfo? info), $"Missing entry: {expected.Path}");
            Assert.AreEqual(expected.Type, info.EntryType == CompoundEntryType.Stream ? "stream" : "storage", expected.Path);
            if (expected.Type == "stream")
                Assert.AreEqual(expected.Size, info.Length, expected.Path);
        }
    }

    /// <summary>
    /// Verifies that the materialized bytes of every stream in each valid reference fixture match the SHA-256 recorded
    /// in the manifest, proving exact extraction with no slack bytes.
    /// </summary>
    /// <param name="kat">The reference fixture row.</param>
    [TestMethod]
    [TestCategory(TestCategories.Regression)]
    [DynamicData(nameof(CompoundReferenceManifest.ValidFixtures), typeof(CompoundReferenceManifest),
        DynamicDataDisplayName = nameof(KatDisplayName.GetDisplayName),
        DynamicDataDisplayNameDeclaringType = typeof(KatDisplayName))]
    public void OpenStream_WhenReferenceFixtureIsValid_ShouldMatchExpectedHashes(CompoundReferenceFixtureKat kat)
    {
        using CompoundFile file = CompoundFile.Open(CompoundFixtures.OpenReference(kat.RelativePath));
        Dictionary<string, string> streams = HashStreams(file.RootStorage);

        foreach (CompoundManifestEntry expected in kat.Entries)
        {
            if (expected.Sha256 is null)
                continue;

            Assert.IsTrue(streams.TryGetValue(expected.Path, out string? actualHash), $"Missing stream: {expected.Path}");
            Assert.AreEqual(expected.Sha256, actualHash, expected.Path);
        }
    }

    /// <summary>
    /// Flattens a storage hierarchy into a path-keyed map of entry metadata.
    /// </summary>
    /// <param name="root">The root storage to walk.</param>
    /// <returns>A map from storage-qualified path to entry metadata.</returns>
    private static Dictionary<string, CompoundEntryInfo> Flatten(CompoundStorage root)
    {
        Dictionary<string, CompoundEntryInfo> map = new(StringComparer.Ordinal);
        void Walk(CompoundStorage storage, string prefix)
        {
            foreach (CompoundEntryInfo info in storage.EnumerateStreams())
                map[Combine(prefix, info.Name)] = info;

            foreach (CompoundStorage child in storage.EnumerateStorages())
            {
                string path = Combine(prefix, child.Name);
                map[path] = child.Stat;
                Walk(child, path);
            }
        }

        Walk(root, string.Empty);
        return map;
    }

    /// <summary>
    /// Hashes every stream in a storage hierarchy, keyed by storage-qualified path.
    /// </summary>
    /// <param name="root">The root storage to walk.</param>
    /// <returns>A map from storage-qualified path to lowercase hexadecimal SHA-256.</returns>
    private static Dictionary<string, string> HashStreams(CompoundStorage root)
    {
        Dictionary<string, string> map = new(StringComparer.Ordinal);
        void Walk(CompoundStorage storage, string prefix)
        {
            foreach (CompoundEntryInfo info in storage.EnumerateStreams())
            {
                using CompoundStream stream = storage.OpenStream(info.Name);
                map[Combine(prefix, info.Name)] = Convert.ToHexString(SHA256.HashData(stream.AsMemory().Span)).ToLowerInvariant();
            }

            foreach (CompoundStorage child in storage.EnumerateStorages())
                Walk(child, Combine(prefix, child.Name));
        }

        Walk(root, string.Empty);
        return map;
    }

    /// <summary>
    /// Combines a path prefix and a child name with a forward slash.
    /// </summary>
    /// <param name="prefix">The parent path, possibly empty.</param>
    /// <param name="name">The child name.</param>
    /// <returns>The combined path.</returns>
    private static string Combine(string prefix, string name) =>
        prefix.Length == 0 ? name : prefix + "/" + name;
}
