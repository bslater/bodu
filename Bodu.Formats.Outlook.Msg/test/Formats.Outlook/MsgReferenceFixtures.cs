using System.Text.Json;
using System.Text.Json.Serialization;
using Bodu.Test.Kat;

namespace Bodu.Formats.Outlook;

/// <summary>
/// Loads the embedded reference-corpus fixtures and their expectations manifest.
/// </summary>
/// <remarks>
/// The corpus files and <c>manifest.json</c> are embedded resources under the
/// <c>Bodu.Formats.Outlook.Msg.Fixtures.Reference</c> logical-name prefix; provenance is recorded in the
/// <c>Fixtures/Reference/NOTICE.md</c> alongside them. The manifest expectations were generated by an independent
/// implementation, so the corpus sweep is a cross-implementation check.
/// </remarks>
internal static class MsgReferenceFixtures
{
    /// <summary>The logical-name prefix of the embedded reference resources.</summary>
    private const string ResourcePrefix = "Bodu.Formats.Outlook.Msg.Fixtures.Reference.";

    /// <summary>The lazily deserialized manifest.</summary>
    private static readonly Lazy<MsgReferenceManifest> s_manifest = new(LoadManifest);

    /// <summary>
    /// Gets the deserialized expectations manifest.
    /// </summary>
    /// <value>The manifest carrying one row per corpus file.</value>
    internal static MsgReferenceManifest Manifest =>
        s_manifest.Value;

    /// <summary>
    /// Opens a corpus fixture as a seekable stream.
    /// </summary>
    /// <param name="classification">The fixture folder: <c>valid</c> or <c>invalid</c>.</param>
    /// <param name="fileName">The fixture file name.</param>
    /// <returns>A stream positioned at the start of the fixture bytes.</returns>
    /// <exception cref="InvalidOperationException">The embedded resource does not exist.</exception>
    internal static MemoryStream OpenStream(string classification, string fileName)
    {
        string resourceName = ResourcePrefix + classification + "." + fileName;
        using Stream stream = typeof(MsgReferenceFixtures).Assembly.GetManifestResourceStream(resourceName)
            ?? throw new InvalidOperationException($"Missing embedded fixture '{resourceName}'.");

        var buffer = new MemoryStream();
        stream.CopyTo(buffer);
        buffer.Position = 0;
        return buffer;
    }

    /// <summary>
    /// Deserializes the embedded manifest.
    /// </summary>
    /// <returns>The manifest.</returns>
    private static MsgReferenceManifest LoadManifest()
    {
        using Stream stream = typeof(MsgReferenceFixtures).Assembly.GetManifestResourceStream(ResourcePrefix + "manifest.json")
            ?? throw new InvalidOperationException("Missing embedded reference manifest.");

        return JsonSerializer.Deserialize<MsgReferenceManifest>(stream)
            ?? throw new InvalidOperationException("The reference manifest deserialized to null.");
    }
}

/// <summary>
/// Represents the reference-corpus expectations manifest.
/// </summary>
/// <param name="Source">The upstream corpus source and license.</param>
/// <param name="GeneratedBy">The independent implementation that generated the expectations.</param>
/// <param name="GeneratedAtUtc">When the manifest was generated.</param>
/// <param name="Fixtures">The per-file expectation rows.</param>
internal sealed record MsgReferenceManifest(
    [property: JsonPropertyName("source")] string Source,
    [property: JsonPropertyName("generatedBy")] string GeneratedBy,
    [property: JsonPropertyName("generatedAtUtc")] string GeneratedAtUtc,
    [property: JsonPropertyName("fixtures")] IReadOnlyList<MsgReferenceFixture> Fixtures);

/// <summary>
/// Represents one corpus file's expectations. Implements <see cref="IKat" /> so data-driven rows display the file
/// name in failure diagnostics.
/// </summary>
/// <param name="File">The fixture file name.</param>
/// <param name="Expected">The classification: <c>valid</c> or <c>invalid</c>.</param>
/// <param name="Sha256">The SHA-256 of the fixture bytes.</param>
/// <param name="Codepage">The declared message code page (valid rows only).</param>
/// <param name="Subject">The expected subject, or <see langword="null" /> when absent.</param>
/// <param name="SenderName">The expected sender display name, or <see langword="null" /> when absent.</param>
/// <param name="RecipientCount">The expected recipient count.</param>
/// <param name="AttachmentCount">The expected attachment count.</param>
/// <param name="HasBodyText">Whether a plain-text body is present.</param>
/// <param name="HasBodyHtml">Whether an HTML body is present.</param>
/// <param name="HasBodyRtf">Whether a compressed-RTF body is present.</param>
public sealed record MsgReferenceFixture(
    [property: JsonPropertyName("file")] string File,
    [property: JsonPropertyName("expected")] string Expected,
    [property: JsonPropertyName("sha256")] string Sha256,
    [property: JsonPropertyName("codepage")] int? Codepage,
    [property: JsonPropertyName("subject")] string? Subject,
    [property: JsonPropertyName("senderName")] string? SenderName,
    [property: JsonPropertyName("recipientCount")] int? RecipientCount,
    [property: JsonPropertyName("attachmentCount")] int? AttachmentCount,
    [property: JsonPropertyName("hasBodyText")] bool? HasBodyText,
    [property: JsonPropertyName("hasBodyHtml")] bool? HasBodyHtml,
    [property: JsonPropertyName("hasBodyRtf")] bool? HasBodyRtf) : IKat
{
    /// <summary>
    /// Gets the display label for data-driven rows.
    /// </summary>
    /// <value>The fixture file name.</value>
    public string Name =>
        File;
}
