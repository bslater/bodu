using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Bodu.Tools.CurrencyCatalogueGenerator;

/// <summary>
/// Reads currencies.json and emits one C# tag file per ISO 4217 entry under the Bodu.Financial Currencies folder.
/// </summary>
internal static class Program
{
    private const string FileHeader = """
        // ---------------------------------------------------------------------------------------------------------------
        // <auto-generated>
        //     This file is generated by tools/CurrencyCatalogueGenerator from currencies.json. Do not edit by hand.
        //     To regenerate: dotnet run --project tools/CurrencyCatalogueGenerator
        // </auto-generated>
        // ---------------------------------------------------------------------------------------------------------------
        #nullable enable

        """;

    private static int Main(string[] args)
    {
        string repoRoot = LocateRepoRoot();
        string inputPath = Path.Combine(repoRoot, "Bodu.Financial", "src", "Financial.Currencies", "currencies.json");
        string outputDir = Path.Combine(repoRoot, "Bodu.Financial", "src", "Financial.Currencies");

        if (!File.Exists(inputPath))
        {
            Console.Error.WriteLine($"Input file not found: {inputPath}");
            return 1;
        }

        Console.WriteLine($"Reading {inputPath}");
        Catalogue catalogue = ReadCatalogue(inputPath);
        Console.WriteLine($"Loaded {catalogue.Currencies.Length} currency entries.");
        ValidateCatalogue(catalogue);

        var existing = new HashSet<string>(
            Directory.EnumerateFiles(outputDir, "*.cs", SearchOption.TopDirectoryOnly).Select(Path.GetFileName)!,
            StringComparer.Ordinal);

        int written = 0;
        int unchanged = 0;
        foreach (CurrencyEntry currency in catalogue.Currencies)
        {
            ValidateEntry(currency);

            string fileName = currency.Iso + ".cs";
            string outputPath = Path.Combine(outputDir, fileName);
            string source = BuildSource(currency);

            if (File.Exists(outputPath) && File.ReadAllText(outputPath) == source)
            {
                unchanged++;
            }
            else
            {
                File.WriteAllText(outputPath, source);
                written++;
            }

            existing.Remove(fileName);
        }

        const string registrationFileName = "GeneratedCurrencyRegistration.cs";
        string registrationPath = Path.Combine(outputDir, registrationFileName);
        string registrationSource = BuildRegistrationSource(catalogue);
        if (File.Exists(registrationPath) && File.ReadAllText(registrationPath) == registrationSource)
        {
            unchanged++;
        }
        else
        {
            File.WriteAllText(registrationPath, registrationSource);
            written++;
        }

        existing.Remove(registrationFileName);

        const string currencyCodeFileName = "CurrencyCode.cs";
        string currencyCodePath = Path.Combine(outputDir, currencyCodeFileName);
        string currencyCodeSource = BuildCurrencyCodeSource(catalogue);
        if (File.Exists(currencyCodePath) && File.ReadAllText(currencyCodePath) == currencyCodeSource)
        {
            unchanged++;
        }
        else
        {
            File.WriteAllText(currencyCodePath, currencyCodeSource);
            written++;
        }

        existing.Remove(currencyCodeFileName);

        int removed = 0;
        foreach (string stale in existing)
        {
            if (string.Equals(stale, "currencies.json", StringComparison.Ordinal))
                continue;
            if (string.Equals(stale, "README.md", StringComparison.Ordinal))
                continue;

            string stalePath = Path.Combine(outputDir, stale);

            // Only remove files this tool generated; never delete hand-authored companions such as
            // CurrencyStatus.cs or CurrencyCodeExtensions.cs that live alongside the generated output.
            if (!File.ReadAllText(stalePath).Contains("<auto-generated>", StringComparison.Ordinal))
                continue;

            Console.WriteLine($"Removing stale file: {stale}");
            File.Delete(stalePath);
            removed++;
        }

        Console.WriteLine($"Done. Wrote {written}, left {unchanged} unchanged, removed {removed}.");
        return 0;
    }

    private static string BuildRegistrationSource(Catalogue catalogue)
    {
        StringBuilder builder = new();
        builder.Append(FileHeader);
        builder.AppendLine("namespace Bodu.Financial.Currencies;");
        builder.AppendLine();
        builder.AppendLine("using global::System.Collections.Generic;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Source-generated registration list of the shipped currency catalogue, consumed by");
        builder.AppendLine("/// <see cref=\"Bodu.Financial.CurrencyRegistry\" /> at static-constructor time.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("internal static class GeneratedCurrencyRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Enumerates the shipped <see cref=\"Bodu.Financial.CurrencyInfo\" /> entries.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <returns>One entry per currency tag type under <c>Bodu.Financial.Currencies</c>.</returns>");
        builder.AppendLine("    public static IEnumerable<global::Bodu.Financial.CurrencyInfo> All()");
        builder.AppendLine("    {");

        foreach (CurrencyEntry currency in catalogue.Currencies)
        {
            string cashIncrement = (currency.CashRoundingIncrement ?? 0m)
                .ToString("0.################", CultureInfo.InvariantCulture);

            string demonetizedExpr;
            if (currency.IsHistoric && !string.IsNullOrEmpty(currency.DemonetizedOn))
            {
                global::System.DateOnly date = global::System.DateOnly.ParseExact(
                    currency.DemonetizedOn,
                    "yyyy-MM-dd",
                    CultureInfo.InvariantCulture);
                demonetizedExpr = $"new global::System.DateOnly({date.Year.ToString(CultureInfo.InvariantCulture)}, " +
                    $"{date.Month.ToString(CultureInfo.InvariantCulture)}, " +
                    $"{date.Day.ToString(CultureInfo.InvariantCulture)})";
            }
            else
            {
                demonetizedExpr = "null";
            }

            string successorExpr = string.IsNullOrEmpty(currency.SuccessorIsoCode)
                ? "null"
                : $"\"{currency.SuccessorIsoCode}\"";

            string englishNameLiteral = ToCSharpStringLiteral(currency.Name);

            builder.Append("        yield return new global::Bodu.Financial.CurrencyInfo(\"")
                .Append(currency.Iso)
                .Append("\", ")
                .Append(currency.MinorUnits.ToString(CultureInfo.InvariantCulture))
                .Append(", ")
                .Append(cashIncrement)
                .Append("m, ")
                .Append(currency.IsHistoric ? "true" : "false")
                .Append(", ")
                .Append(demonetizedExpr)
                .Append(", ")
                .Append(successorExpr)
                .Append(", ")
                .Append(englishNameLiteral)
                .Append(", ")
                .Append(currency.Numeric.ToString(CultureInfo.InvariantCulture))
                .AppendLine(");");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string BuildCurrencyCodeSource(Catalogue catalogue)
    {
        StringBuilder builder = new();
        builder.Append(FileHeader);
        builder.AppendLine("namespace Bodu.Financial.Currencies;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Source-generated enumeration of the ISO 4217 currencies shipped with Bodu.Financial.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("/// <remarks>");
        builder.AppendLine("/// Each member name is the three-letter ISO 4217 alphabetic code; each member value is the");
        builder.AppendLine("/// corresponding ISO 4217 numeric code. Both active and historic / demonetized currencies are");
        builder.AppendLine("/// included; a member's lifecycle is declared by its <see cref=\"CurrencyStatusAttribute\" /> and");
        builder.AppendLine("/// can be queried via <see cref=\"CurrencyCodeExtensions.GetStatus(CurrencyCode)\" />. The");
        builder.AppendLine("/// <see cref=\"None\" /> sentinel (value 0) represents the absence of a currency.");
        builder.AppendLine("/// </remarks>");
        builder.AppendLine("public enum CurrencyCode");
        builder.AppendLine("{");

        builder.AppendLine("    /// <summary>No currency; sentinel for a currency-less or default-initialized value.</summary>");
        builder.AppendLine("    [CurrencyStatus(CurrencyStatus.None)]");
        builder.AppendLine("    None = 0,");

        foreach (CurrencyEntry currency in catalogue.Currencies)
        {
            builder.AppendLine();

            builder.Append("    /// <summary>")
                .Append(currency.Name)
                .Append(" (numeric ")
                .Append(currency.Numeric.ToString(CultureInfo.InvariantCulture))
                .Append(currency.IsHistoric ? "; historic" : string.Empty)
                .AppendLine(").</summary>");
            builder.Append("    [CurrencyStatus(CurrencyStatus.")
                .Append(currency.IsHistoric ? "Historic" : "Active")
                .AppendLine(")]");
            builder.Append("    ")
                .Append(currency.Iso)
                .Append(" = ")
                .Append(currency.Numeric.ToString(CultureInfo.InvariantCulture))
                .AppendLine(",");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static Catalogue ReadCatalogue(string path)
    {
        string json = File.ReadAllText(path);
        var options = new JsonSerializerOptions
        {
            ReadCommentHandling = JsonCommentHandling.Skip,
            AllowTrailingCommas = true,
            PropertyNameCaseInsensitive = true,
        };

        Catalogue? catalogue = JsonSerializer.Deserialize<Catalogue>(json, options);
        if (catalogue is null || catalogue.Currencies is null)
            throw new InvalidDataException(CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_CatalogueDeserialize);

        return catalogue;
    }

    private static void ValidateCatalogue(Catalogue catalogue)
    {
        var seenNumeric = new Dictionary<int, string>();
        foreach (CurrencyEntry currency in catalogue.Currencies)
        {
            if (seenNumeric.TryGetValue(currency.Numeric, out string? existingIso))
            {
                throw new InvalidDataException(string.Format(
                    CultureInfo.CurrentCulture,
                    CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_DuplicateNumericCode,
                    currency.Numeric,
                    existingIso,
                    currency.Iso));
            }

            seenNumeric[currency.Numeric] = currency.Iso;
        }
    }

    private static void ValidateEntry(CurrencyEntry currency)
    {
        if (currency.Iso is null || currency.Iso.Length != 3)
            throw new InvalidDataException(string.Format(CultureInfo.CurrentCulture, CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_IsoCodeLength, currency.Iso));

        for (int i = 0; i < 3; i++)
        {
            char c = currency.Iso[i];
            if (c < 'A' || c > 'Z')
                throw new InvalidDataException(string.Format(CultureInfo.CurrentCulture, CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_IsoCodeNotUpper, currency.Iso));
        }

        if (currency.Numeric < 0 || currency.Numeric > 999)
            throw new InvalidDataException(string.Format(CultureInfo.CurrentCulture, CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_NumericCodeRange, currency.Numeric, currency.Iso));

        if (currency.MinorUnits < 0 || currency.MinorUnits > 4)
            throw new InvalidDataException(string.Format(CultureInfo.CurrentCulture, CurrencyCatalogueGeneratorResourceStrings.IO_Invalid_MinorUnitsRange, currency.MinorUnits, currency.Iso));
    }

    private static string BuildSource(CurrencyEntry currency)
    {
        StringBuilder builder = new();
        builder.Append(FileHeader);
        builder.AppendLine("namespace Bodu.Financial.Currencies;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.Append("/// Identifies ").Append(currency.Iso).Append(" (").Append(currency.Name).AppendLine(") at the type-system level.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("/// <remarks>");
        builder.Append("/// ISO 4217 numeric code <c>").Append(currency.Numeric.ToString(CultureInfo.InvariantCulture)).Append("</c>; minor-unit precision <c>").Append(currency.MinorUnits.ToString(CultureInfo.InvariantCulture)).AppendLine("</c>.");
        if (currency.IsHistoric)
        {
            builder.Append("/// Historic — demonetized");
            if (!string.IsNullOrEmpty(currency.DemonetizedOn))
                builder.Append(" on ").Append(currency.DemonetizedOn);
            if (!string.IsNullOrEmpty(currency.SuccessorIsoCode))
                builder.Append(", replaced by ").Append(currency.SuccessorIsoCode);
            builder.AppendLine(".");
        }
        builder.AppendLine("/// </remarks>");
        builder.Append("public sealed class ").Append(currency.Iso).AppendLine(" : ICurrency");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Gets the ISO 4217 alphabetic code for the currency.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <value>The three-letter ISO 4217 code.</value>");
        builder.Append("    public static string IsoCode => \"").Append(currency.Iso).AppendLine("\";");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Gets the ISO 4217 three-digit numeric code for the currency.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <value>The three-digit ISO 4217 numeric code.</value>");
        builder.Append("    public static int NumericCode => ").Append(currency.Numeric.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Gets the number of fractional digits in the currency's minor unit.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <value>The currency's minor-unit precision.</value>");
        builder.Append("    public static int MinorUnits => ").Append(currency.MinorUnits.ToString(CultureInfo.InvariantCulture)).AppendLine(";");

        if (currency.CashRoundingIncrement is { } increment && increment != 0m)
        {
            builder.AppendLine();
            builder.AppendLine("    /// <summary>");
            builder.AppendLine("    /// Gets the smallest cash denomination of the currency, in the major unit.");
            builder.AppendLine("    /// </summary>");
            builder.AppendLine("    /// <value>The cash-rounding increment.</value>");
            builder.Append("    public static decimal CashRoundingIncrement => ")
                .Append(increment.ToString("0.################", CultureInfo.InvariantCulture))
                .AppendLine("m;");
        }

        if (currency.IsHistoric)
        {
            builder.AppendLine();
            builder.AppendLine("    /// <summary>");
            builder.AppendLine("    /// Gets a value indicating that the currency has been demonetized.");
            builder.AppendLine("    /// </summary>");
            builder.AppendLine("    /// <value><see langword=\"true\" /> — this is a historic currency.</value>");
            builder.AppendLine("    public static bool IsHistoric => true;");

            if (!string.IsNullOrEmpty(currency.DemonetizedOn))
            {
                builder.AppendLine();
                builder.AppendLine("    /// <summary>");
                builder.AppendLine("    /// Gets the date the currency was withdrawn from circulation.");
                builder.AppendLine("    /// </summary>");
                builder.AppendLine("    /// <value>The demonetization date.</value>");
                builder.Append("    public static global::System.DateOnly? DemonetizedOn => new global::System.DateOnly(");
                var date = global::System.DateOnly.ParseExact(currency.DemonetizedOn, "yyyy-MM-dd", CultureInfo.InvariantCulture);
                builder.Append(date.Year.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(date.Month.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(date.Day.ToString(CultureInfo.InvariantCulture))
                    .AppendLine(");");
            }

            if (!string.IsNullOrEmpty(currency.SuccessorIsoCode))
            {
                builder.AppendLine();
                builder.AppendLine("    /// <summary>");
                builder.AppendLine("    /// Gets the ISO 4217 alphabetic code of the currency that replaced this one.");
                builder.AppendLine("    /// </summary>");
                builder.AppendLine("    /// <value>The successor currency's ISO code.</value>");
                builder.Append("    public static string? SuccessorIsoCode => \"")
                    .Append(currency.SuccessorIsoCode)
                    .AppendLine("\";");
            }
        }

        builder.AppendLine();
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Gets the English-language name of the currency.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <value>The currency's English name in singular Title Case.</value>");
        builder.Append("    public static string EnglishName => ")
            .Append(ToCSharpStringLiteral(currency.Name))
            .AppendLine(";");

        builder.AppendLine();
        builder.AppendLine("    /// <summary>");
        builder.Append("    /// Prevents instantiation of the <see cref=\"").Append(currency.Iso).AppendLine("\" /> tag type.");
        builder.AppendLine("    /// </summary>");
        builder.Append("    private ").Append(currency.Iso).AppendLine("()");
        builder.AppendLine("    {");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string ToCSharpStringLiteral(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (char c in value)
        {
            switch (c)
            {
                case '\\': builder.Append("\\\\"); break;
                case '"': builder.Append("\\\""); break;
                case '\r': builder.Append("\\r"); break;
                case '\n': builder.Append("\\n"); break;
                case '\t': builder.Append("\\t"); break;
                default: builder.Append(c); break;
            }
        }
        builder.Append('"');
        return builder.ToString();
    }

    private static string LocateRepoRoot()
    {
        DirectoryInfo? dir = new(Directory.GetCurrentDirectory());
        while (dir is not null)
        {
            if (File.Exists(Path.Combine(dir.FullName, "bodu.slnx")))
                return dir.FullName;
            dir = dir.Parent;
        }

        throw new InvalidOperationException(CurrencyCatalogueGeneratorResourceStrings.Op_Invalid_RepositoryRootNotFound);
    }

    private sealed record Catalogue
    {
        public CurrencyEntry[] Currencies { get; init; } = [];
    }

    private sealed record CurrencyEntry
    {
        public string Iso { get; init; } = string.Empty;
        public int Numeric { get; init; }
        public int MinorUnits { get; init; }
        public string Name { get; init; } = string.Empty;
        public decimal? CashRoundingIncrement { get; init; }
        public bool IsHistoric { get; init; }
        public string? DemonetizedOn { get; init; }
        public string? SuccessorIsoCode { get; init; }
    }
}
