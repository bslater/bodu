    /// <summary>
    /// Verifies that requesting an unsupported hash size throws <see cref="ArgumentOutOfRangeException" />.
    /// </summary>
    [TestMethod]
    public void Ctor_WhenHashSizeIsUnsupported_ShouldThrowExactly()
