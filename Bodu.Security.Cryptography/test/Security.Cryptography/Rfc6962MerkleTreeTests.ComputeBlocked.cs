    /// <summary>
    /// A read-only stream that never returns more than a fixed number of bytes per read, so a caller that treats a
    /// short read as the end of the stream is caught.
    /// </summary>
    private sealed class ThrottledStream : Stream
    {
        /// <summary>The bytes to serve.</summary>
        private readonly byte[] _bytes;

        /// <summary>The most bytes any single read returns.</summary>
        private readonly int _maxBytesPerRead;

        /// <summary>The number of bytes already served.</summary>
        private int _position;

        /// <summary>
        /// Initializes a new instance of the <see cref="ThrottledStream" /> class.
        /// </summary>
        /// <param name="bytes">The bytes to serve.</param>
        /// <param name="maxBytesPerRead">The most bytes any single read returns.</param>
        internal ThrottledStream(byte[] bytes, int maxBytesPerRead)
        {
            _bytes = bytes;
            _maxBytesPerRead = maxBytesPerRead;
        }

        /// <inheritdoc />
        public override bool CanRead => true;

        /// <inheritdoc />
        public override bool CanSeek => false;

        /// <inheritdoc />
        public override bool CanWrite => false;

        /// <inheritdoc />
        public override long Length => _bytes.Length;

        /// <inheritdoc />
        public override long Position
        {
            get => _position;
            set => throw new NotSupportedException();
        }

        /// <inheritdoc />
        public override int Read(byte[] buffer, int offset, int count)
        {
            int available = Math.Min(Math.Min(count, _maxBytesPerRead), _bytes.Length - _position);
            if (available <= 0)
                return 0;

            Buffer.BlockCopy(_bytes, _position, buffer, offset, available);
            _position += available;
            return available;
        }

        /// <inheritdoc />
        public override void Flush()
        {
            // Nothing to flush: the stream is read-only.
        }

        /// <inheritdoc />
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();

        /// <inheritdoc />
        public override void SetLength(long value) => throw new NotSupportedException();

        /// <inheritdoc />
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
    }

    /// <summary>
    /// Verifies that a supplied <see cref="MerkleTreeDiagnostics" /> receives a trace that validates on its own, holds
    /// one leaf per block, and ends at the root the call returned — for every leaf count up to sixteen, so promoted
    /// leftovers are covered as well as full pairs.
    /// </summary>
    [TestMethod]
    public void ComputeRootOfBlocks_WhenDiagnosticsAreSupplied_ShouldRecordAValidatingTraceEndingAtTheRoot()
    {
        Rfc6962MerkleTree tree = CreateTree();

        for (int leafCount = 0; leafCount <= 16; leafCount++)
        {
            using var source = new MemoryStream(BlockModeInput(leafCount * VectorBlockSize));
            var diagnostics = new MerkleTreeDiagnostics();

            byte[] root = tree.ComputeRootOfBlocks(source, VectorBlockSize, diagnostics);

            Assert.IsTrue(
                diagnostics.Validate(SHA256.Create, out IReadOnlyList<string> errors),
                string.Join("; ", errors));
            Assert.AreEqual(leafCount, diagnostics.GetLevel(0).Count, $"leaf count {leafCount}");

            if (leafCount == 0)
                Assert.IsNull(diagnostics.Root, "an empty tree records no node");
            else
                Assert.AreEqual(Hex(root), Hex(diagnostics.Root!.Hash), $"leaf count {leafCount}");
        }
    }
