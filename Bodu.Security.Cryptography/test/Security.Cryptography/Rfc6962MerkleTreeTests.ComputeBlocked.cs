    /// <summary>
    /// Verifies that a stream delivering its bytes in small, uneven pieces yields the same root as one delivering
    /// them all at once, so a short read is never mistaken for the end of the stream.
    /// </summary>
    /// <param name="maxBytesPerRead">The most bytes the stream will return from a single read.</param>
    [TestMethod]
    [DataRow(1)]
    [DataRow(2)]
    [DataRow(3)]
    [DataRow(5)]
    [DataRow(7)]
    public void ComputeBlocked_WhenStreamReturnsShortReads_ShouldProduceTheSameRoot(int maxBytesPerRead)
    {
        Rfc6962MerkleTree tree = CreateTree();
        byte[] input = BlockModeInput(33);

        using var whole = new MemoryStream(input);
        string expected = Hex(tree.ComputeBlocked(whole, VectorBlockSize).Root);

        using var throttled = new ThrottledStream(input, maxBytesPerRead);
        MerkleBlockComputation computation = tree.ComputeBlocked(throttled, VectorBlockSize);

        Assert.AreEqual("31dce6ff9c5ac1336d203f99ea214a31eaba3429a3316fdc7eb7dfa1e787e9ec", expected);
        Assert.AreEqual(expected, Hex(computation.Root));
        Assert.AreEqual(33, computation.InputLength);
        Assert.AreEqual(9, computation.LeafHashes.Count);
    }

