    /// <summary>
    /// Returns the first <paramref name="length" /> bytes of the concatenation of
    /// <c>SHA-256(BE64(counter))</c> from counter zero — the stream the FallbackPlan vectors are taken over.
    /// </summary>
    /// <param name="length">The number of bytes to generate.</param>
    /// <returns>The generated byte sequence.</returns>
    internal static byte[] CounterStream(int length)
    {
        byte[] bytes = new byte[length];
        Span<byte> input = stackalloc byte[sizeof(ulong)];
        Span<byte> block = stackalloc byte[SHA256.HashSizeInBytes];

        ulong counter = 0;
        int written = 0;
        while (written < length)
        {
            BinaryPrimitives.WriteUInt64BigEndian(input, counter++);
            SHA256.HashData(input, block);

            int take = Math.Min(block.Length, length - written);
            block[..take].CopyTo(bytes.AsSpan(written));
            written += take;
        }

        return bytes;
    }

    /// <summary>
    /// Verifies that the streamed block-mode root reproduces the published Merkle Tree Hash, including a short final
    /// block and a zero-length stream.
    /// </summary>
    /// <param name="kat">The input length and its expected root.</param>
    [TestMethod]
    [DynamicData(nameof(BlockModeRoots), DynamicDataDisplayName = nameof(KatDisplayName.GetDisplayName), DynamicDataDisplayNameDeclaringType = typeof(KatDisplayName))]
    [TestCategory("Regression")]
    public void ComputeBlocked_WhenReadingAStream_ShouldReproduceRfc6962MerkleTreeHash(ValidKat<int, string> kat)
    {
        Rfc6962MerkleTree tree = CreateTree();
        using var stream = new MemoryStream(BlockModeInput(kat.Input));

        MerkleBlockComputation computation = tree.ComputeBlocked(stream, VectorBlockSize);

        Assert.AreEqual(kat.Expected, Hex(computation.Root));
        Assert.AreEqual(kat.Input, computation.InputLength);
        Assert.AreEqual(VectorBlockSize, computation.BlockSize);
        Assert.AreEqual(MerkleBlocks.BlockCount(kat.Input, VectorBlockSize), computation.LeafHashes.Count);
    }

    /// <summary>
    /// Verifies that the logarithmic-memory fold produces the same root as the leaf-retaining pass for every leaf
    /// count from zero to sixty-four, which is where the two constructions could most easily disagree.
    /// </summary>
    /// <remarks>
    /// The fold pushes each leaf as a one-leaf subtree and combines equal-sized neighbours, then folds the remainder
    /// right to left. That reproduces RFC 6962's shape only if every pending entry is a perfect subtree, so a
    /// disagreement at any non-power-of-two count would reveal a broken merge condition.
    /// </remarks>
    [TestMethod]
    [TestCategory("Regression")]
    public void ComputeRootOfBlocks_WhenFoldingIncrementally_ShouldAgreeWithTheLeafRetainingPass()
    {
        Rfc6962MerkleTree tree = CreateTree();

        for (int leafCount = 0; leafCount <= 64; leafCount++)
        {
            // A trailing partial block as well as exact multiples, so both tail shapes are covered.
            foreach (int tail in (int[])[0, 1])
            {
                int length = (leafCount * VectorBlockSize) + tail;
                if (leafCount == 0 && tail == 0)
                    length = 0;

                byte[] input = BlockModeInput(length);

                using var retaining = new MemoryStream(input);
                using var folding = new MemoryStream(input);

                string expected = Hex(tree.ComputeBlocked(retaining, VectorBlockSize).Root);
                string actual = Hex(tree.ComputeRootOfBlocks(folding, VectorBlockSize));

                Assert.AreEqual(expected, actual, $"length {length} ({leafCount} full blocks + {tail})");
            }
        }
    }

    /// <summary>
    /// Verifies that the incremental fold still agrees with the leaf-retaining pass at large leaf counts, either side
    /// of a power of two, where a wrong merge condition would surface as a mismatch.
    /// </summary>
    /// <param name="leafCount">The number of one-byte blocks, and so of leaves.</param>
    /// <remarks>
    /// The fold's peak memory holds one pending subtree per set bit in the leaf count, so counts such as 65 535
    /// (sixteen set bits) and 65 536 (one) exercise opposite extremes of its stack depth.
    /// </remarks>
    [TestMethod]
    [TestCategory("Regression")]
    [DataRow(1023)]
    [DataRow(1024)]
    [DataRow(1025)]
    [DataRow(65535)]
    [DataRow(65536)]
    [DataRow(65537)]
    public void ComputeRootOfBlocks_WhenLeafCountIsLarge_ShouldAgreeWithTheLeafRetainingPass(int leafCount)
    {
        Rfc6962MerkleTree tree = CreateTree();
        byte[] input = BlockModeInput(leafCount);

        using var retaining = new MemoryStream(input);
        using var folding = new MemoryStream(input);

        MerkleBlockComputation computation = tree.ComputeBlocked(retaining, blockSize: 1);

        Assert.AreEqual(leafCount, computation.LeafHashes.Count);
        Assert.AreEqual(Hex(computation.Root), Hex(tree.ComputeRootOfBlocks(folding, blockSize: 1)));
    }

