using System.Security.Cryptography;

namespace Bodu.Security.Cryptography;

/// <summary>
/// Pins <see cref="MerkleTreeHash" /> at a fan-out of two to RFC 6962's Merkle Tree Hash, so the two cannot drift
/// apart again.
/// </summary>
/// <remarks>
/// <para>
/// <see cref="MerkleTreeHash" /> uses RFC 6962's domain separation — a leaf is <c>H(0x00 || block)</c> and an
/// internal node <c>H(0x01 || children)</c> — and, at a fan-out of two, RFC 6962's tree: it reduces level by level and
/// promotes a lone leftover node unchanged, which visits exactly the nodes of the recursive definition that splits at
/// the largest power of two strictly below the leaf count. The empty input is the empty tree, whose root is the hash
/// of zero bytes.
/// </para>
/// <para>
/// Every expected value below was computed independently from RFC 6962 §2.1's definitions rather than transcribed
/// from this implementation. The inputs are the first <em>L</em> bytes of the sequence <c>0x00, 0x01, 0x02, …</c>
/// at a block size of 4 and a fan-out of 2. The non-power-of-two rows are the ones the previous level-by-level
/// reduction got wrong — it re-hashed the leftover as a one-child node — and they are what a regression would show
/// up in first.
/// </para>
/// </remarks>
public partial class MerkleTreeHashTests
{
    /// <summary>The block size at which the tree is compared with RFC 6962.</summary>
    private const int ConformanceBlockSize = 4;

    /// <summary>The fan-out at which the tree is RFC 6962's.</summary>
    private const int ConformanceFanOut = 2;

    /// <summary>
    /// Returns the first <paramref name="length" /> bytes of the sequence <c>0x00, 0x01, 0x02, …</c>, wrapping at
    /// 256.
    /// </summary>
    /// <param name="length">The number of bytes to generate.</param>
    /// <returns>The generated byte sequence.</returns>
    private static byte[] ConformanceInput(int length)
    {
        byte[] bytes = new byte[length];
        for (int i = 0; i < length; i++)
            bytes[i] = (byte)(i & 0xFF);

        return bytes;
    }

    /// <summary>
    /// Computes the root <see cref="MerkleTreeHash" /> produces over <see cref="ConformanceInput(int)" /> at the
    /// comparison configuration.
    /// </summary>
    /// <param name="length">The number of input bytes.</param>
    /// <returns>The root hash, lowercase hex-encoded.</returns>
    private static string ConformanceRoot(int length)
    {
        using var hasher = new MerkleTreeHash(SHA256.Create, ConformanceBlockSize, ConformanceFanOut);
        return Convert.ToHexString(hasher.ComputeHash(ConformanceInput(length))).ToLowerInvariant();
    }

    /// <summary>
    /// Verifies that for a power-of-two leaf count the root equals RFC 6962's Merkle Tree Hash — the rows on which
    /// even a one-child re-hash would have agreed, because no level has a lone leftover.
    /// </summary>
    /// <param name="length">The number of input bytes.</param>
    /// <param name="expectedLeafCount">The number of leaves those bytes produce.</param>
    /// <param name="expectedRoot">RFC 6962's Merkle Tree Hash over the same leaves, lowercase hex.</param>
    [TestMethod]
    [TestCategory("Regression")]
    [DataRow(1, 1, "96a296d224f285c67bee93c30f8a309157f0daa35dc5b87e410b78630a09cfc7")]
    [DataRow(4, 1, "a498efa8d0759e7b704095853db9bc1ef8cf65af37bed9d006c4b2917e695061")]
    [DataRow(5, 2, "a568e8449ea491fdb4a261e3e75d2a8562b7c66887ad89cd590df667eae30146")]
    [DataRow(8, 2, "000134e55e67854e1a3d28a78c6392b02623c2505580b0f9d571e0b4d3e2257f")]
    [DataRow(13, 4, "311ae2a2c5f7b96b71ad76148419619697a19c5d61f894a9dcc254c8363341e9")]
    [DataRow(16, 4, "516c43cb9e4f82fe70437703f0a41649c5fd963ba5f4be8b736dca20bae05bdd")]
    [DataRow(32, 8, "4caa28905e0e6530cced23948c7f3a575f09c618644c66e36f8bd5bc19b2f11c")]
    public void ComputeHash_WhenLeafCountIsAPowerOfTwo_ShouldMatchRfc6962MerkleTreeHash(
        int length, int expectedLeafCount, string expectedRoot)
    {
        Assert.AreEqual(
            expectedLeafCount,
            (length + ConformanceBlockSize - 1) / ConformanceBlockSize,
            "the row's stated leaf count must match the block arithmetic");

        Assert.AreEqual(expectedRoot, ConformanceRoot(length));
    }

    /// <summary>
    /// Verifies that for a non-power-of-two leaf count the root equals RFC 6962's Merkle Tree Hash — the rows that
    /// require a lone leftover to be promoted unchanged rather than re-hashed as a one-child node.
    /// </summary>
    /// <param name="length">The number of input bytes.</param>
    /// <param name="expectedLeafCount">The number of leaves those bytes produce.</param>
    /// <param name="expectedRoot">RFC 6962's Merkle Tree Hash over the same leaves, lowercase hex.</param>
    [TestMethod]
    [TestCategory("Regression")]
    [DataRow(9, 3, "7d0d764930953cf7bda9cfaf927efb27e0c74b7601ea8e5ef87a1b03e7ac85c2")]
    [DataRow(12, 3, "3b469d6b2565374bf3f9d7405627a59e3dba9a3207f3c52b06db08e7190e1f14")]
    [DataRow(17, 5, "557a6fa29055fbfb4466b8068539aa5e6c9b2c1500624cab414631484e5bc551")]
    [DataRow(20, 5, "0a30d6148fc3d1c38bc90624148f2021ee9d4a72d2fdcb53dcba91e46237f6d0")]
    [DataRow(28, 7, "6a648b436a7ba0966d61d03e31033b8e6a5d69dcbf73777afb508ab1f0260a63")]
    [DataRow(33, 9, "31dce6ff9c5ac1336d203f99ea214a31eaba3429a3316fdc7eb7dfa1e787e9ec")]
    public void ComputeHash_WhenLeafCountIsNotAPowerOfTwo_ShouldMatchRfc6962MerkleTreeHash(
        int length, int expectedLeafCount, string expectedRoot)
    {
        Assert.AreEqual(
            expectedLeafCount,
            (length + ConformanceBlockSize - 1) / ConformanceBlockSize,
            "the row's stated leaf count must match the block arithmetic");

        Assert.AreEqual(expectedRoot, ConformanceRoot(length));
    }

    /// <summary>
    /// Verifies that a zero-length input yields RFC 6962's empty-tree root, <c>MTH({}) = H()</c>, the hash of the
    /// empty string, rather than throwing.
    /// </summary>
    [TestMethod]
    [TestCategory("Regression")]
    public void ComputeHash_WhenInputIsEmpty_ShouldReturnRfc6962EmptyTreeRoot()
    {
        using var hasher = new MerkleTreeHash(SHA256.Create, ConformanceBlockSize, ConformanceFanOut);

        Assert.AreEqual(
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
            Convert.ToHexString(hasher.ComputeHash([])).ToLowerInvariant());
    }
}
