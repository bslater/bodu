using System.Threading.Tasks;
using Bodu.CodeStyle.XmlDocumentation.Analyzers.Diagnostics;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.CodeAnalysis.Testing.Verifiers;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace Bodu.CodeStyle.XmlDocumentation.Analyzers.Test;

[TestClass]
public sealed class XmlDocTypeParamRequiresShortContentAnalyzerTests
{
    private static CSharpAnalyzerTest<XmlDocTypeParamRequiresShortContentAnalyzer, MSTestVerifier> CreateTest(string source) =>
        new CSharpAnalyzerTest<XmlDocTypeParamRequiresShortContentAnalyzer, MSTestVerifier>
        {
            TestCode = source,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
        };

    /// <summary>
    /// Verifies that a single-sentence <c>&lt;typeparam&gt;</c> whose rendered line fits the 120-char budget
    /// does not trigger BODU1406.
    /// </summary>
    [TestMethod]
    [TestCategory(TestCategories.Smoke)]
    public async Task Analyze_WhenTypeParamIsShortSingleSentence_ShouldNotReport()
    {
        var source =
            "/// <summary>Sample.</summary>\r\n" +
            "/// <typeparam name=\"T\">The element type.</typeparam>\r\n" +
            "public sealed class Sample<T>\r\n" +
            "{\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        await CreateTest(source).RunAsync(TestContext.CancellationTokenSource.Token);
    }

    /// <summary>
    /// Verifies that a multi-sentence <c>&lt;typeparam&gt;</c> whose rendered line exceeds the 120-char
    /// budget triggers BODU1406 at the element's start tag.
    /// </summary>
    [TestMethod]
    [TestCategory(TestCategories.Smoke)]
    public async Task Analyze_WhenTypeParamIsLongMultiSentence_ShouldReportBODU1406()
    {
        // Rendered line: 4 (/// ) + 20 (<typeparam name="T">) + 96 (content) + 12 (</typeparam>) = 132 chars,
        // which exceeds the default 120-char budget. The first sentence ("The element type.") would fit on a
        // single line on its own, so the rule fires.
        var source =
            "/// <summary>Sample.</summary>\r\n" +
            "/// <typeparam name=\"T\">The element type. Some additional explanatory prose that should be relocated to a remarks block.</typeparam>\r\n" +
            "public sealed class Sample<T>\r\n" +
            "{\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        CSharpAnalyzerTest<XmlDocTypeParamRequiresShortContentAnalyzer, MSTestVerifier> test = CreateTest(source);
        test.ExpectedDiagnostics.Add(
            new DiagnosticResult(DiagnosticDescriptors.XmlDocTypeParamRequiresShortContent)
                .WithSpan(2, 5, 2, 25));

        await test.RunAsync(TestContext.CancellationTokenSource.Token);
    }

    /// <summary>
    /// Verifies that a long single-sentence <c>&lt;typeparam&gt;</c> (no internal sentence boundary) does not
    /// trigger BODU1406 — the rule defers to the format analyzer's BODU1011 in that case so the auto-fix is
    /// always able to succeed when BODU1406 fires.
    /// </summary>
    [TestMethod]
    public async Task Analyze_WhenTypeParamIsLongButSingleSentence_ShouldNotReport()
    {
        var source =
            "/// <summary>Sample.</summary>\r\n" +
            "/// <typeparam name=\"T\">A very long single sentence that describes the element type without containing any internal sentence boundary</typeparam>\r\n" +
            "public sealed class Sample<T>\r\n" +
            "{\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        await CreateTest(source).RunAsync(TestContext.CancellationTokenSource.Token);
    }

    /// <summary>
    /// Verifies that a file carrying the standard <c>&lt;auto-generated /&gt;</c> header is skipped entirely
    /// even when its <c>&lt;typeparam&gt;</c> would otherwise trigger BODU1406.
    /// </summary>
    [TestMethod]
    public async Task Analyze_WhenAutoGeneratedMarkerPresent_ShouldSkip()
    {
        var source =
            "// <auto-generated />\r\n" +
            "/// <summary>Sample.</summary>\r\n" +
            "/// <typeparam name=\"T\">The element type. Some additional explanatory prose that should be relocated to a remarks block.</typeparam>\r\n" +
            "public sealed class Sample<T>\r\n" +
            "{\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        await CreateTest(source).RunAsync(TestContext.CancellationTokenSource.Token);
    }

    public TestContext TestContext { get; set; } = null!;
}
