    /// <summary>
    /// Creates an analyzer test over a single source file with the given path, for the cases that depend on the file
    /// name.
    /// </summary>
    /// <param name="path">The path of the source file.</param>
    /// <param name="source">The source text.</param>
    /// <returns>The configured analyzer test.</returns>
    private static CSharpAnalyzerTest<XmlDocFormatAnalyzer, MSTestVerifier> CreateNamedTest(string path, string source)
    {
        var test = new CSharpAnalyzerTest<XmlDocFormatAnalyzer, MSTestVerifier>
        {
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
        };
        test.TestState.Sources.Add((path, source));

        return test;
    }
