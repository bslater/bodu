    /// <summary>
    /// Verifies that a hand-written file whose name ends in <c>AssemblyAttributes.cs</c> is analyzed, since Roslyn
    /// treats a file as generated by its name only for the <c>.designer</c>, <c>.generated</c>, <c>.g</c> and
    /// <c>.g.i</c> suffixes and the <c>TemporaryGeneratedFile_</c> prefix.
    /// </summary>
    [TestMethod]
    public async Task Analyze_WhenHandWrittenFileNameEndsInAssemblyAttributes_ShouldReport()
    {
        var source =
            "public sealed class Sample\r\n" +
            "{\r\n" +
            "    /// <summary>Bar.</summary>\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        CSharpAnalyzerTest<XmlDocFormatAnalyzer, MSTestVerifier> test = CreateNamedTest("/0/FooAssemblyAttributes.cs", source);
        test.ExpectedDiagnostics.Add(
            new DiagnosticResult(DiagnosticDescriptors.XmlDocSummary)
                .WithSpan("/0/FooAssemblyAttributes.cs", 3, 5, 4, 1));

        await test.RunAsync(TestContext.CancellationTokenSource.Token);
    }

