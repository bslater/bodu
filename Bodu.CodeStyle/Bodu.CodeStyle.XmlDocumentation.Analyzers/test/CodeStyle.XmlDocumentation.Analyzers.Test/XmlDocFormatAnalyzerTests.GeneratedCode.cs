    /// <summary>
    /// Verifies that a file carrying the banner is analyzed when <c>generated_code = false</c> in .editorconfig
    /// tells Roslyn it is not generated.
    /// </summary>
    [TestMethod]
    public async Task Analyze_WhenGeneratedCodeOptionIsFalse_ShouldReport()
    {
        var source =
            "// <auto-generated />\r\n" +
            "public sealed class Sample\r\n" +
            "{\r\n" +
            "    /// <summary>Bar.</summary>\r\n" +
            "    public int X { get; set; }\r\n" +
            "}\r\n";

        CSharpAnalyzerTest<XmlDocFormatAnalyzer, MSTestVerifier> test = CreateTest(source);
        test.TestState.AnalyzerConfigFiles.Add(("/.editorconfig", "root = true\r\n\r\n[*.cs]\r\ngenerated_code = false\r\n"));
        test.TestBehaviors |= TestBehaviors.SkipGeneratedCodeCheck;
        test.ExpectedDiagnostics.Add(
            new DiagnosticResult(DiagnosticDescriptors.XmlDocSummary)
                .WithSpan(4, 5, 5, 1));

        await test.RunAsync(TestContext.CancellationTokenSource.Token);
    }

