#!/usr/bin/env bash
# ---------------------------------------------------------------------------------------------------------------
# check-policy.sh
#
# Deterministic (Tier-1) coding-policy gate for the Bodu solution. Enforces the mechanically
# checkable rules from CLAUDE.md that the Roslyn analyzers do not already cover, and reports
# violations as GitHub Actions error annotations (::error file=...::) plus a human summary.
#
# DIFF-SCOPED BY DESIGN. A mature tree carries a few grandfathered stragglers (e.g. the
# TestHelpers files without a banner, or the Bodu.Text.Yaml literal exception messages). To
# introduce a BLOCKING gate without a big-bang cleanup, this script only judges what a change
# actually adds: added FILES for whole-file rules, added LINES for line rules. Pre-existing
# violations are grandfathered until the offending line is touched; new code must comply.
#
# Checks:
#   1. Banner       - every ADDED .cs file starts with the copyright banner (CLAUDE.md > File Header).
#   2. FileScopedNs - every ADDED .cs file uses a file-scoped `namespace X;` (CLAUDE.md > Namespace Style).
#   3. ResxMessage  - no string-literal exception message on ADDED src lines; messages come from the
#                     *ResourceStrings resx via ThrowHelper (CLAUDE.md > Static Text and Exception Messages).
#   4. Dash         - no em-dash (U+2014) or en-dash (U+2013) on an ADDED line of any text file, outside the
#                     files bld/policy/dash-allowlist.txt names (CLAUDE.md > Documentation Tone > Punctuation).
#
# Generated files are exempt from 1 and 2, recognized by the rule Roslyn's analyzers apply (see is_generated), so
# the script and the analyzers never disagree about a file. Test code (paths containing /test/) is exempt from 3 (the
# resx rule is a production-code policy).
#
# Usage:  bld/check-policy.sh [BASE_REF] [HEAD_REF]
#   BASE_REF  merge-base side of the diff. Default: $POLICY_BASE_REF, else `git merge-base origin/master HEAD`.
#   HEAD_REF  tip side of the diff.        Default: $POLICY_HEAD_REF, else HEAD.
#
# Exit code: 0 when the change is clean, 1 when one or more violations are found.
# ---------------------------------------------------------------------------------------------------------------
set -uo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

base_ref="${1:-${POLICY_BASE_REF:-}}"
head_ref="${2:-${POLICY_HEAD_REF:-HEAD}}"

if [ -z "$base_ref" ]; then
  base_ref="$(git merge-base origin/master "$head_ref" 2>/dev/null || git merge-base master "$head_ref" 2>/dev/null || echo "")"
fi
if [ -z "$base_ref" ]; then
  echo "::error::check-policy.sh could not resolve a base ref for diffing. Pass BASE_REF or set POLICY_BASE_REF." >&2
  exit 2
fi

violations=0

emit() {
  # emit <file> <line> <message>
  local file="$1" line="$2" msg="$3"
  echo "::error file=${file},line=${line}::${msg}"
  echo "  ✗ ${file}:${line} - ${msg}" >&2
  violations=$((violations + 1))
}

# Reads a C# file up to its first token and exits 0 when a // or /* */ comment before it contains <autogenerated or
# <auto-generated, as Roslyn's GeneratedCodeUtilities.BeginsWithAutoGeneratedComment does. Documentation comments
# (/// and /** */, which every project here parses as documentation) are not comments to Roslyn's test, and a
# preprocessor directive line is passed over. Conditional compilation is not evaluated: a banner in a disabled #if
# region counts here, where Roslyn reads it as disabled text.
read -r -d '' generated_banner_awk <<'AWK'
BEGIN { bom = "\357\273\277"; found = 0; inblock = 0 }
{
  line = $0
  if (NR == 1 && index(line, bom) == 1) line = substr(line, length(bom) + 1)
  n = length(line)
  i = 1
  while (i <= n) {
    if (inblock) {
      j = index(substr(line, i), "*/")
      if (j == 0) { text = text substr(line, i) "\n"; break }
      text = text substr(line, i, j - 1)
      i += j + 1
      inblock = 0
      if (!doc && text ~ /<auto-?generated/) { found = 1; exit }
      continue
    }
    c = substr(line, i, 1)
    if (c == " " || c == "\t" || c == "\r" || c == "\f" || c == "\v") { i++; continue }
    if (c == "#" && substr(line, 1, i - 1) ~ /^[ \t\f\v]*$/) break
    if (substr(line, i, 2) == "//") {
      doc = (substr(line, i, 3) == "///" && substr(line, i, 4) != "////")
      if (!doc && substr(line, i) ~ /<auto-?generated/) { found = 1; exit }
      break
    }
    if (substr(line, i, 2) == "/*") {
      doc = (substr(line, i, 3) == "/**" && substr(line, i, 4) != "/**/")
      inblock = 1
      text = ""
      i += 2
      continue
    }
    exit
  }
}
END { exit (found ? 0 : 1) }
AWK

is_generated() {
  # is_generated <file>
  #
  # Roslyn's rule (GeneratedCodeUtilities.IsGeneratedCode): the file name, in any case, begins with
  # TemporaryGeneratedFile_ or ends in .designer, .generated, .g or .g.i before its extension; or a comment before the
  # first token carries the banner (generated_banner_awk). The generated_code .editorconfig option, which can override
  # both for the analyzers, is not read; the repository does not set it.
  local f="$1" name stem
  name="${f##*/}"
  name="${name,,}"
  case "$name" in
    temporarygeneratedfile_*) return 0 ;;
  esac
  if [[ "$name" == *.* ]]; then
    stem="${name%.*}"
    case "$stem" in
      *.designer|*.generated|*.g|*.g.i) return 0 ;;
    esac
  fi
  [ -f "$f" ] && LC_ALL=C awk "$generated_banner_awk" "$f" && return 0
  return 1
}

# ── Whole-file rules over ADDED .cs files ──────────────────────────────────────────────────────
while IFS= read -r f; do
  [ -z "$f" ] && continue
  case "$f" in *.cs) ;; *) continue ;; esac
  [ -f "$f" ] || continue
  is_generated "$f" && continue

  # 1. Banner in the first few lines.
  if ! head -5 "$f" | grep -q '<copyright file='; then
    emit "$f" 1 "New file is missing the Bodu copyright banner (CLAUDE.md > Source File Conventions > File Header)."
  fi

  # 2. File-scoped namespace. A compliant file declares `namespace X;`. Flag the block form
  #    `namespace X { ... }`. Files with no namespace at all (rare: global-scope helpers) are skipped.
  if grep -qE '^[[:space:]]*namespace[[:space:]]+[A-Za-z0-9_.]+[[:space:]]*;' "$f"; then
    : # file-scoped - compliant
  elif grep -qE '^[[:space:]]*namespace[[:space:]]+[A-Za-z0-9_.]+' "$f"; then
    ns_line="$(grep -nE '^[[:space:]]*namespace[[:space:]]+[A-Za-z0-9_.]+' "$f" | head -1 | cut -d: -f1)"
    emit "$f" "${ns_line:-1}" "New file uses a block-scoped namespace; use a file-scoped 'namespace X;' (CLAUDE.md > Namespace Style)."
  fi
done < <(git diff --diff-filter=A --name-only "$base_ref" "$head_ref" -- '*.cs')

# ── Line rules over ADDED lines in production src ───────────────────────────────────────────────
# Collect changed src .cs files (exclude tests), then read only the added lines with their new
# line numbers from a zero-context diff.
mapfile -t src_files < <(
  git diff --diff-filter=ACMR --name-only "$base_ref" "$head_ref" -- '*.cs' \
    | grep -E '/src/' \
    | grep -vE '/test/' || true
)

if [ "${#src_files[@]}" -gt 0 ]; then
  current=""
  newline=0
  while IFS= read -r line; do
    case "$line" in
      '+++ b/'*)
        current="${line#+++ b/}"
        ;;
      '@@ '*)
        # @@ -a,b +c,d @@  → next added line starts at c
        hunk="${line#@@ -}"
        hunk="${hunk#*+}"
        newline="${hunk%%,*}"; newline="${newline%% *}"
        ;;
      '+'*)
        [ "${line:0:3}" = "+++" ] && continue
        content="${line:1}"
        trimmed="${content#"${content%%[![:space:]]*}"}"
        # skip comment lines - doc examples and commented code are not live throws
        case "$trimmed" in
          //*|/\**|\**) newline=$((newline + 1)); continue ;;
        esac
        # 3. Literal exception message: `throw new <T>Exception("...`. A nameof-only argument
        #    (e.g. ArgumentNullException(nameof(x))) carries no literal and is not flagged.
        if printf '%s' "$trimmed" | grep -qE 'throw new [A-Za-z_][A-Za-z0-9_]*Exception\([[:space:]]*(\$?@?")'; then
          emit "$current" "$newline" "Exception message is a string literal; source it from the *ResourceStrings resx via ThrowHelper (CLAUDE.md > Static Text and Exception Messages)."
        fi
        newline=$((newline + 1))
        ;;
      ' '*)
        newline=$((newline + 1))
        ;;
    esac
  done < <(git diff --unified=0 "$base_ref" "$head_ref" -- "${src_files[@]}")
fi

# ── Line rule over ADDED lines in every text file ───────────────────────────────────────────────
# 4. Dash. The characters are written as UTF-8 byte escapes so this script does not contain them itself, and
#    matched as quoted substrings, which compares the bytes in any locale. Binary files add no '+' lines, so they
#    are never judged.
em_dash=$'\xe2\x80\x94'
en_dash=$'\xe2\x80\x93'
dash_pathspec=(.)
while IFS= read -r exempt; do
  [ -n "$exempt" ] && dash_pathspec+=(":(exclude)${exempt}")
done < <(sed -e 's/#.*//' -e 's/[[:space:]]*$//' bld/policy/dash-allowlist.txt 2>/dev/null | grep -v '^[[:space:]]*$' || true)

current=""
newline=0
while IFS= read -r line; do
  case "$line" in
    '+++ b/'*)
      current="${line#+++ b/}"
      ;;
    '@@ '*)
      hunk="${line#@@ -}"
      hunk="${hunk#*+}"
      newline="${hunk%%,*}"; newline="${newline%% *}"
      ;;
    '+'*)
      [ "${line:0:3}" = "+++" ] && continue
      if [[ "$line" == *"$em_dash"* || "$line" == *"$en_dash"* ]]; then
        emit "$current" "$newline" "Line contains an em-dash or en-dash; use a hyphen: ' - ' for an aside, '-' in a range (CLAUDE.md > Documentation Tone > Punctuation). A dash that is test data belongs in bld/policy/dash-allowlist.txt."
      fi
      newline=$((newline + 1))
      ;;
  esac
done < <(git diff --unified=0 --diff-filter=ACMR "$base_ref" "$head_ref" -- "${dash_pathspec[@]}")

echo >&2
if [ "$violations" -eq 0 ]; then
  echo "Policy gate: OK - no Tier-1 violations in the change." >&2
  exit 0
fi
echo "Policy gate: ${violations} violation(s) found." >&2
exit 1
