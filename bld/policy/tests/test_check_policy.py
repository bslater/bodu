"""Tests for bld/check-policy.sh.

The script is run end to end: each test copies it into a temporary git repository, commits a base, adds the files under
test in a second commit, and runs the script over the two commits, as the Policy Gate runs it over a pull request.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest

SCRIPT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "check-policy.sh")

BANNER = (
    "// ---------------------------------------------------------------------------------------------------------------\n"
    '// <copyright file="Sample.cs" company="Bodu Pty. Ltd.">\n'
    "// Copyright (c) Bodu Pty. Ltd. All rights reserved.\n"
    "// </copyright>\n"
    "// ---------------------------------------------------------------------------------------------------------------\n"
)

GENERATED_BLOCK = (
    "// ---------------------------------------------------------------------------------------------------------------\n"
    "// <auto-generated />\n"
    "// ---------------------------------------------------------------------------------------------------------------\n"
)

# A block-scoped namespace breaks the file-scoped namespace rule, which exempts only generated files, so a file that
# ends with it shows whether the script treats the file as generated.
BLOCK_NAMESPACE = "namespace Bodu.Sample\n{\n    internal static class Sample\n    {\n    }\n}\n"

NAMESPACE_RULE = "uses a block-scoped namespace"
BANNER_RULE = "missing the Bodu copyright banner"


class PolicyRun:
    """The outcome of one run of the script: its exit code and everything it wrote."""

    def __init__(self, returncode: int, output: str) -> None:
        self.returncode = returncode
        self.output = output


def run_policy(files: dict[str, str]) -> PolicyRun:
    """Commits a base, adds the given files in a second commit, and runs the script over the two commits."""
    with tempfile.TemporaryDirectory() as root:
        os.makedirs(os.path.join(root, "bld"))
        shutil.copy(SCRIPT, os.path.join(root, "bld", "check-policy.sh"))

        env = dict(os.environ)
        env.update(
            GIT_AUTHOR_NAME="Policy Test",
            GIT_AUTHOR_EMAIL="policy@example.invalid",
            GIT_COMMITTER_NAME="Policy Test",
            GIT_COMMITTER_EMAIL="policy@example.invalid",
            GIT_CONFIG_GLOBAL=os.devnull,
            GIT_CONFIG_NOSYSTEM="1",
        )

        def git(*args: str) -> str:
            return subprocess.run(
                ["git", *args], cwd=root, env=env, check=True, capture_output=True, text=True
            ).stdout.strip()

        git("init", "-q")
        git("add", "-A")
        git("commit", "-q", "-m", "base")
        base = git("rev-parse", "HEAD")

        for path, content in files.items():
            full = os.path.join(root, path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
        git("add", "-A")
        git("commit", "-q", "-m", "change")

        result = subprocess.run(
            ["bash", "bld/check-policy.sh", base, "HEAD"], cwd=root, env=env, capture_output=True, text=True
        )
        return PolicyRun(result.returncode, result.stdout + result.stderr)


class GeneratedFileTests(unittest.TestCase):
    """The files the whole-file rules exempt as generated, held to the rule Roslyn's analyzers apply.

    Roslyn treats a file as generated when its name ends in .designer, .generated, .g or .g.i before the extension, or
    begins with TemporaryGeneratedFile_, ignoring case; or when a // or /* */ comment before the first token of the file
    contains <autogenerated or <auto-generated. A documentation comment does not count, and a comment after the first
    token does not count.
    """

    def assert_exempt(self, path: str, content: str) -> None:
        run = run_policy({path: content})
        self.assertEqual(0, run.returncode, run.output)
        self.assertNotIn(NAMESPACE_RULE, run.output)

    def assert_judged(self, path: str, content: str) -> None:
        run = run_policy({path: content})
        self.assertEqual(1, run.returncode, run.output)
        self.assertIn(NAMESPACE_RULE, run.output)

    def test_is_generated_when_banner_opens_the_file_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.cs", GENERATED_BLOCK + "\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_banner_follows_the_copyright_header_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.cs", BANNER + "\n" + GENERATED_BLOCK + "\nusing System;\n\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_banner_follows_a_directive_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.cs", "#nullable enable\n" + GENERATED_BLOCK + BLOCK_NAMESPACE)

    def test_is_generated_when_banner_is_a_multi_line_comment_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.cs", "/*\n * <auto-generated>\n * </auto-generated>\n */\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_banner_is_spelled_without_a_hyphen_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.cs", "// <autogenerated />\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_name_ends_in_designer_in_any_case_should_exempt_it(self) -> None:
        self.assert_exempt("src/Strings.Designer.cs", BLOCK_NAMESPACE)
        self.assert_exempt("src/Strings.designer.cs", BLOCK_NAMESPACE)

    def test_is_generated_when_name_ends_in_g_or_g_i_should_exempt_it(self) -> None:
        self.assert_exempt("src/Sample.g.cs", BLOCK_NAMESPACE)
        self.assert_exempt("src/Sample.g.i.cs", BLOCK_NAMESPACE)
        self.assert_exempt("src/Sample.Generated.cs", BLOCK_NAMESPACE)

    def test_is_generated_when_name_begins_with_temporary_generated_file_should_exempt_it(self) -> None:
        self.assert_exempt("src/TemporaryGeneratedFile_0123.cs", BLOCK_NAMESPACE)

    def test_is_generated_when_file_has_no_banner_should_judge_it(self) -> None:
        self.assert_judged("src/Sample.cs", BANNER + "\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_banner_trails_the_first_token_should_judge_it(self) -> None:
        run = run_policy({"src/Sample.cs": "using System; // <auto-generated />\n\n" + BLOCK_NAMESPACE})
        self.assertEqual(1, run.returncode, run.output)
        self.assertIn(NAMESPACE_RULE, run.output)
        self.assertIn(BANNER_RULE, run.output)

    def test_is_generated_when_banner_is_a_documentation_comment_should_judge_it(self) -> None:
        self.assert_judged("src/Sample.cs", "/// <auto-generated />\n" + BLOCK_NAMESPACE)

    def test_is_generated_when_name_only_contains_g_should_judge_it(self) -> None:
        self.assert_judged("src/Sample.g.Extensions.cs", BANNER + "\n" + BLOCK_NAMESPACE)


if __name__ == "__main__":
    unittest.main()
