using System.Globalization;
using Bodu.Test.Kat;

namespace Bodu.Globalization.Calendar;

/// <summary>
/// Loads the embedded Hebrew-calendar observance vector table — fifty Gregorian years of independently computed dates
/// for every <c>global-jewish</c> catalogue observance — as KAT rows for <c>[DynamicData]</c> binding.
/// </summary>
/// <remarks>
/// <para>
/// The vectors are generated by <c>tools/generate-hebrew-observance-vectors.py</c>, an independent implementation of
/// the classical Hebrew-calendar arithmetic, and were cross-verified at generation time against the Hebcal-verified
/// 2023–2026 rows and the <see cref="System.Globalization.HebrewCalendar" /> projection; the file's provenance header
/// records the details.
/// </para>
/// </remarks>
internal static class HebrewObservanceVectors
{
    /// <summary>The logical name of the embedded vector file.</summary>
    private const string ResourceName = "Bodu.Globalization.Calendar.Fixtures.Vectors.HebrewObservances-1990-2039.csv";

    /// <summary>
    /// Gets the vector rows, one per (Gregorian year, observance) pair, each carrying the expected date.
    /// </summary>
    /// <value>The KAT rows for <c>[DynamicData]</c> binding.</value>
    public static IEnumerable<object[]> Rows
    {
        get
        {
            using Stream stream = typeof(HebrewObservanceVectors).Assembly.GetManifestResourceStream(ResourceName)
                ?? throw new InvalidOperationException($"Embedded vector file '{ResourceName}' not found.");
            using StreamReader reader = new(stream);

            while (reader.ReadLine() is { } line)
            {
                if (line.Length == 0 || line.StartsWith('#'))
                    continue;

                string[] fields = line.Split(',');
                var year = int.Parse(fields[0], CultureInfo.InvariantCulture);
                string observanceId = fields[1];
                var expected = DateOnly.Parse(fields[2], CultureInfo.InvariantCulture);

                yield return
                [
                    new ValidKat<(int Year, string ObservanceId), DateOnly>(
                        $"{observanceId} {year}",
                        (year, observanceId),
                        expected),
                ];
            }
        }
    }
}
