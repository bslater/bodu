using System.Globalization;
using Bodu.Test.Kat;

namespace Bodu.Globalization.Calendar;

/// <summary>
/// Loads the embedded Zoroastrian observance vector table — fifty Gregorian years of independently computed dates for
/// every <c>global-zoroastrian</c> catalogue observance — as KAT rows for <c>[DynamicData]</c> binding.
/// </summary>
/// <remarks>
/// <para>
/// The vectors are generated by <c>tools/generate-persian-observance-vectors.py</c> (with the <c>zoroastrian</c>
/// argument), an independent implementation of the official Solar Hijri new-year rule, and were cross-verified at
/// generation time against the <see cref="System.Globalization.PersianCalendar" /> projection; the file's provenance
/// header records the details.
/// </para>
/// <para>
/// Zartosht No-Diso (Dey 11) straddles the Gregorian new year and can land zero or two times in one Gregorian year, so
/// each KAT row carries the full ordered occurrence list for its (year, observance) pair.
/// </para>
/// </remarks>
internal static class ZoroastrianObservanceVectors
{
    /// <summary>The logical name of the embedded vector file.</summary>
    private const string ResourceName = "Bodu.Globalization.Calendar.Fixtures.Vectors.ZoroastrianObservances-1990-2039.csv";

    /// <summary>
    /// Gets the vector rows, one per (Gregorian year, observance) pair, each carrying the expected ordered occurrence
    /// list for the year.
    /// </summary>
    /// <value>The KAT rows for <c>[DynamicData]</c> binding.</value>
    public static IEnumerable<object[]> Rows
    {
        get
        {
            Dictionary<(int Year, string ObservanceId), List<DateOnly>> table = new();

            using (Stream stream = typeof(ZoroastrianObservanceVectors).Assembly.GetManifestResourceStream(ResourceName)
                ?? throw new InvalidOperationException($"Embedded vector file '{ResourceName}' not found."))
            using (StreamReader reader = new(stream))
            {
                while (reader.ReadLine() is { } line)
                {
                    if (line.Length == 0 || line.StartsWith('#'))
                        continue;

                    string[] fields = line.Split(',');
                    var year = int.Parse(fields[0], CultureInfo.InvariantCulture);
                    string observanceId = fields[1];
                    var date = DateOnly.Parse(fields[2], CultureInfo.InvariantCulture);

                    if (!table.TryGetValue((year, observanceId), out List<DateOnly>? dates))
                        table[(year, observanceId)] = dates = [];

                    dates.Add(date);
                }
            }

            foreach (((int year, string observanceId), List<DateOnly> dates) in table)
            {
                dates.Sort();

                yield return
                [
                    new ValidKat<(int Year, string ObservanceId), IReadOnlyList<DateOnly>>(
                        $"{observanceId} {year}",
                        (year, observanceId),
                        dates),
                ];
            }
        }
    }
}
