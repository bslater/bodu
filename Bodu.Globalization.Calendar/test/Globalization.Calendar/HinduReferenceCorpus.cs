using System.Globalization;
using System.Text;

namespace Bodu.Globalization.Calendar;

/// <summary>
/// Strict loader for the calcal Modern Hindu Reference corpus committed under
/// <c>corpus/hindu/data/normalized/hindu-reference-daily.csv</c>.
/// </summary>
/// <remarks>
/// <para>
/// Parsing is deliberately unforgiving: invariant culture, exact <c>yyyy-MM-dd</c> dates, rejection of duplicate
/// (model, date) keys, no defaulting of absent values, and per-model completeness validation (one row per Gregorian
/// date across the model's inclusive range). The corpus file is generated by the pinned R oracle and committed as a
/// permanent repository artifact; the reconciliation tests fail — not skip — when it cannot be located.
/// </para>
/// </remarks>
internal static class HinduReferenceCorpus
{
    /// <summary>The corpus file path relative to the repository root.</summary>
    private const string RelativePath = "corpus/hindu/data/normalized/hindu-reference-daily.csv";

    /// <summary>
    /// Attempts to locate the corpus file by walking up from the test base directory to the repository root.
    /// </summary>
    /// <returns>The corpus file path, or <see langword="null" /> when the repository root or file is absent.</returns>
    public static string? FindCorpusFile()
    {
        for (DirectoryInfo? dir = new(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "bodu.slnx")))
            {
                string path = Path.Combine(dir.FullName, RelativePath.Replace('/', Path.DirectorySeparatorChar));
                return File.Exists(path) ? path : null;
            }
        }

        return null;
    }

    /// <summary>
    /// Loads and validates the corpus rows for one calendar model.
    /// </summary>
    /// <param name="path">The corpus file path.</param>
    /// <param name="calendarModel">The calendar model to load, for example <c>modern-hindu-lunar</c>.</param>
    /// <returns>The rows for the model, keyed by Gregorian date, in chronological order.</returns>
    /// <exception cref="InvalidOperationException">
    /// The file is structurally invalid: a required column is missing, a value fails strict parsing, a (model, date)
    /// key repeats, or the model's date coverage has gaps.
    /// </exception>
    public static SortedDictionary<DateOnly, HinduReferenceCorpusRow> Load(string path, string calendarModel)
    {
        string[] lines = File.ReadAllLines(path, Encoding.UTF8);
        int headerIndex = Array.FindIndex(lines, static line => line.Length > 0 && !line.StartsWith('#'));
        if (headerIndex < 0)
            throw new InvalidOperationException("The corpus file has no header row.");

        Dictionary<string, int> columns = new(StringComparer.Ordinal);
        string[] headers = SplitCsv(lines[headerIndex]);
        for (int i = 0; i < headers.Length; i++)
            columns[headers[i]] = i;

        foreach (string required in new[] { "gregorian_date", "fixed_date", "calendar_model", "source_version" })
        {
            if (!columns.ContainsKey(required))
                throw new InvalidOperationException($"The corpus file is missing the required column '{required}'.");
        }

        SortedDictionary<DateOnly, HinduReferenceCorpusRow> rows = new();

        for (int i = headerIndex + 1; i < lines.Length; i++)
        {
            if (lines[i].Length == 0)
                continue;

            string[] fields = SplitCsv(lines[i]);
            if (Field(fields, columns, "calendar_model") != calendarModel)
                continue;

            var date = DateOnly.ParseExact(Field(fields, columns, "gregorian_date")!, "yyyy-MM-dd", CultureInfo.InvariantCulture);
            var row = new HinduReferenceCorpusRow(
                date,
                (long)double.Parse(Field(fields, columns, "fixed_date")!, CultureInfo.InvariantCulture),
                calendarModel,
                OptionalInt(fields, columns, "lunar_year"),
                OptionalInt(fields, columns, "lunar_month"),
                OptionalInt(fields, columns, "lunar_day"),
                OptionalBool(fields, columns, "is_leap_month"),
                OptionalInt(fields, columns, "solar_year"),
                OptionalInt(fields, columns, "solar_month"),
                OptionalInt(fields, columns, "solar_day"),
                Field(fields, columns, "source_version") ?? throw new InvalidOperationException("source_version is required."));

            if (!rows.TryAdd(date, row))
                throw new InvalidOperationException($"Duplicate corpus key: {calendarModel} {date:yyyy-MM-dd}.");
        }

        if (rows.Count > 0)
        {
            int expected = rows.Keys.Max().DayNumber - rows.Keys.Min().DayNumber + 1;
            if (rows.Count != expected)
                throw new InvalidOperationException(
                    $"The '{calendarModel}' corpus covers {rows.Count} rows but its inclusive range spans {expected} days.");
        }

        return rows;
    }

    /// <summary>
    /// Reads a named field, returning <see langword="null" /> for an absent column or empty cell.
    /// </summary>
    /// <param name="fields">The split row.</param>
    /// <param name="columns">The header index map.</param>
    /// <param name="name">The column name.</param>
    /// <returns>The trimmed cell text, or <see langword="null" />.</returns>
    private static string? Field(string[] fields, Dictionary<string, int> columns, string name)
    {
        if (!columns.TryGetValue(name, out int index) || index >= fields.Length)
            return null;

        string value = fields[index];
        return value.Length == 0 ? null : value;
    }

    /// <summary>
    /// Parses an optional integer cell strictly; an empty cell is <see langword="null" />, never zero.
    /// </summary>
    /// <param name="fields">The split row.</param>
    /// <param name="columns">The header index map.</param>
    /// <param name="name">The column name.</param>
    /// <returns>The parsed value, or <see langword="null" />.</returns>
    private static int? OptionalInt(string[] fields, Dictionary<string, int> columns, string name) =>
        Field(fields, columns, name) is { } text ? int.Parse(text, CultureInfo.InvariantCulture) : null;

    /// <summary>
    /// Parses an optional boolean cell (R emits <c>TRUE</c>/<c>FALSE</c>); an empty cell is <see langword="null" />.
    /// </summary>
    /// <param name="fields">The split row.</param>
    /// <param name="columns">The header index map.</param>
    /// <param name="name">The column name.</param>
    /// <returns>The parsed value, or <see langword="null" />.</returns>
    private static bool? OptionalBool(string[] fields, Dictionary<string, int> columns, string name) =>
        Field(fields, columns, name) switch
        {
            null => null,
            "TRUE" or "true" or "True" => true,
            "FALSE" or "false" or "False" => false,
            { } other => throw new InvalidOperationException($"Unparseable boolean '{other}' in column '{name}'."),
        };

    /// <summary>
    /// Splits one RFC 4180 CSV line, honoring double-quoted fields.
    /// </summary>
    /// <param name="line">The line to split.</param>
    /// <returns>The unquoted field values.</returns>
    private static string[] SplitCsv(string line)
    {
        List<string> fields = new();
        var current = new StringBuilder();
        bool quoted = false;

        for (int i = 0; i < line.Length; i++)
        {
            char c = line[i];
            if (quoted)
            {
                if (c == '"' && i + 1 < line.Length && line[i + 1] == '"')
                {
                    current.Append('"');
                    i++;
                }
                else if (c == '"')
                {
                    quoted = false;
                }
                else
                {
                    current.Append(c);
                }
            }
            else if (c == '"')
            {
                quoted = true;
            }
            else if (c == ',')
            {
                fields.Add(current.ToString());
                current.Clear();
            }
            else
            {
                current.Append(c);
            }
        }

        fields.Add(current.ToString());
        return [.. fields];
    }
}
