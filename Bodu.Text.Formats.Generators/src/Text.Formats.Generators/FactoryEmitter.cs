using System.Text;

namespace Bodu.Text.Formats.Generators;

/// <summary>
/// Renders the generated factory source for a <see cref="FactoryModel" />.
/// </summary>
internal static class FactoryEmitter
{
    /// <summary>
    /// Emits the complete generated source for the model's factory.
    /// </summary>
    /// <param name="model">The factory model.</param>
    /// <returns>The generated C# source text.</returns>
    public static string Emit(FactoryModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        int indent = 0;
        if (model.Namespace.Length > 0)
        {
            builder.AppendLine($"namespace {model.Namespace}");
            builder.AppendLine("{");
            indent++;
        }

        foreach (string containing in model.ContainingTypes)
        {
            AppendLine(builder, indent, containing);
            AppendLine(builder, indent, "{");
            indent++;
        }

        AppendLine(builder, indent, model.DeclarationHeader);
        AppendLine(builder, indent, "{");
        indent++;

        if (model.Kind == FactoryKind.Delimited)
            EmitDelimitedFactory(builder, indent, model);
        else
            EmitIniFactory(builder, indent, model);

        indent--;
        AppendLine(builder, indent, "}");

        for (int i = 0; i < model.ContainingTypes.Count; i++)
        {
            indent--;
            AppendLine(builder, indent, "}");
        }

        if (model.Namespace.Length > 0)
            builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Emits the delimited record factory: the static <c>DelimitedFactory</c> property and its nested implementation.
    /// </summary>
    /// <param name="builder">The output builder.</param>
    /// <param name="indent">The current indent level.</param>
    /// <param name="model">The factory model.</param>
    private static void EmitDelimitedFactory(StringBuilder builder, int indent, FactoryModel model)
    {
        string contract = $"global::Bodu.Text.Delimited.IDelimitedRecordFactory<{model.TypeName}>";

        AppendLine(builder, indent, $"/// <summary>Gets the generated delimited record factory for <see cref=\"{model.TypeName}\" />.</summary>");
        AppendLine(builder, indent, $"{model.Accessibility} static {contract} DelimitedFactory {{ get; }} = new GeneratedDelimitedRecordFactory();");
        AppendLine(builder, indent, string.Empty);
        AppendLine(builder, indent, "/// <summary>The generated reflection-free delimited record factory.</summary>");
        AppendLine(builder, indent, $"private sealed class GeneratedDelimitedRecordFactory : {contract}");
        AppendLine(builder, indent, "{");
        indent++;

        EmitNamesField(builder, indent, model, "HeaderNames");
        AppendLine(builder, indent, string.Empty);
        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, "public global::System.Collections.Generic.IReadOnlyList<string> Headers => HeaderNames;");
        AppendLine(builder, indent, string.Empty);

        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, $"public string[] GetFields({model.TypeName} record)");
        AppendLine(builder, indent, "{");
        AppendLine(builder, indent + 1, "return new string[]");
        AppendLine(builder, indent + 1, "{");
        foreach (MemberModel member in model.Members)
            AppendLine(builder, indent + 2, $"{BuildToStringExpression(member, "record")},");
        AppendLine(builder, indent + 1, "};");
        AppendLine(builder, indent, "}");
        AppendLine(builder, indent, string.Empty);

        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, $"public {model.TypeName} Create(string[] fields, global::System.Collections.Generic.IReadOnlyList<string> headers)");
        AppendLine(builder, indent, "{");
        AppendLine(builder, indent + 1, $"var result = new {model.TypeName}();");
        AppendLine(builder, indent + 1, "if (headers.Count == 0)");
        AppendLine(builder, indent + 1, "{");
        for (int i = 0; i < model.Members.Count; i++)
        {
            AppendLine(builder, indent + 2, $"if (fields.Length > {i})");
            AppendLine(builder, indent + 3, $"result.{model.Members[i].PropertyName} = {BuildFromStringExpression(model.Members[i], $"fields[{i}]")};");
        }

        AppendLine(builder, indent + 2, "return result;");
        AppendLine(builder, indent + 1, "}");
        AppendLine(builder, indent + 1, string.Empty);
        AppendLine(builder, indent + 1, "int limit = fields.Length < headers.Count ? fields.Length : headers.Count;");
        AppendLine(builder, indent + 1, "for (int i = 0; i < limit; i++)");
        AppendLine(builder, indent + 2, "Bind(result, headers[i], fields[i]);");
        AppendLine(builder, indent + 1, string.Empty);
        AppendLine(builder, indent + 1, "return result;");
        AppendLine(builder, indent, "}");
        AppendLine(builder, indent, string.Empty);

        EmitBindMethod(builder, indent, model);

        indent--;
        AppendLine(builder, indent, "}");
    }

    /// <summary>
    /// Emits the INI section factory: the static <c>IniFactory</c> property and its nested implementation.
    /// </summary>
    /// <param name="builder">The output builder.</param>
    /// <param name="indent">The current indent level.</param>
    /// <param name="model">The factory model.</param>
    private static void EmitIniFactory(StringBuilder builder, int indent, FactoryModel model)
    {
        string contract = $"global::Bodu.Text.Ini.IIniSectionFactory<{model.TypeName}>";
        const string Pair = "global::System.Collections.Generic.KeyValuePair<string, string>";

        AppendLine(builder, indent, $"/// <summary>Gets the generated INI section factory for <see cref=\"{model.TypeName}\" />.</summary>");
        AppendLine(builder, indent, $"{model.Accessibility} static {contract} IniFactory {{ get; }} = new GeneratedIniSectionFactory();");
        AppendLine(builder, indent, string.Empty);
        AppendLine(builder, indent, "/// <summary>The generated reflection-free INI section factory.</summary>");
        AppendLine(builder, indent, $"private sealed class GeneratedIniSectionFactory : {contract}");
        AppendLine(builder, indent, "{");
        indent++;

        EmitNamesField(builder, indent, model, "KeyNames");
        AppendLine(builder, indent, string.Empty);
        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, "public global::System.Collections.Generic.IReadOnlyList<string> Keys => KeyNames;");
        AppendLine(builder, indent, string.Empty);

        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, $"public global::System.Collections.Generic.IEnumerable<{Pair}> GetEntries({model.TypeName} section)");
        AppendLine(builder, indent, "{");
        AppendLine(builder, indent + 1, $"return new {Pair}[]");
        AppendLine(builder, indent + 1, "{");
        foreach (MemberModel member in model.Members)
            AppendLine(builder, indent + 2, $"new {Pair}(\"{Escape(member.WireName)}\", {BuildToStringExpression(member, "section")}),");
        AppendLine(builder, indent + 1, "};");
        AppendLine(builder, indent, "}");
        AppendLine(builder, indent, string.Empty);

        AppendLine(builder, indent, "/// <inheritdoc />");
        AppendLine(builder, indent, $"public {model.TypeName} Create(global::System.Collections.Generic.IEnumerable<{Pair}> entries)");
        AppendLine(builder, indent, "{");
        AppendLine(builder, indent + 1, $"var result = new {model.TypeName}();");
        AppendLine(builder, indent + 1, $"foreach ({Pair} entry in entries)");
        AppendLine(builder, indent + 2, "Bind(result, entry.Key, entry.Value);");
        AppendLine(builder, indent + 1, string.Empty);
        AppendLine(builder, indent + 1, "return result;");
        AppendLine(builder, indent, "}");
        AppendLine(builder, indent, string.Empty);

        EmitBindMethod(builder, indent, model);

        indent--;
        AppendLine(builder, indent, "}");
    }

    /// <summary>
    /// Emits the static wire-name array backing <c>Headers</c> / <c>Keys</c>.
    /// </summary>
    /// <param name="builder">The output builder.</param>
    /// <param name="indent">The current indent level.</param>
    /// <param name="model">The factory model.</param>
    /// <param name="fieldName">The emitted field name.</param>
    private static void EmitNamesField(StringBuilder builder, int indent, FactoryModel model, string fieldName)
    {
        AppendLine(builder, indent, "/// <summary>The resolved wire names, in declaration order.</summary>");
        AppendLine(builder, indent, $"private static readonly string[] {fieldName} = new string[]");
        AppendLine(builder, indent, "{");
        foreach (MemberModel member in model.Members)
            AppendLine(builder, indent + 1, $"\"{Escape(member.WireName)}\",");
        AppendLine(builder, indent, "};");
    }

    /// <summary>
    /// Emits the shared <c>Bind</c> helper that assigns one wire name/value pair to the result instance, matching names
    /// ordinally first and case-insensitively as a fallback.
    /// </summary>
    /// <param name="builder">The output builder.</param>
    /// <param name="indent">The current indent level.</param>
    /// <param name="model">The factory model.</param>
    private static void EmitBindMethod(StringBuilder builder, int indent, FactoryModel model)
    {
        AppendLine(builder, indent, "/// <summary>Assigns one decoded wire name/value pair to the result.</summary>");
        AppendLine(builder, indent, "/// <param name=\"result\">The instance being built.</param>");
        AppendLine(builder, indent, "/// <param name=\"name\">The wire name.</param>");
        AppendLine(builder, indent, "/// <param name=\"value\">The decoded value.</param>");
        AppendLine(builder, indent, $"private static void Bind({model.TypeName} result, string name, string value)");
        AppendLine(builder, indent, "{");
        AppendLine(builder, indent + 1, "switch (name)");
        AppendLine(builder, indent + 1, "{");
        foreach (MemberModel member in model.Members)
        {
            AppendLine(builder, indent + 2, $"case \"{Escape(member.WireName)}\":");
            AppendLine(builder, indent + 3, $"result.{member.PropertyName} = {BuildFromStringExpression(member, "value")};");
            AppendLine(builder, indent + 3, "return;");
        }

        AppendLine(builder, indent + 2, "default:");
        AppendLine(builder, indent + 3, "break;");
        AppendLine(builder, indent + 1, "}");
        AppendLine(builder, indent + 1, string.Empty);
        foreach (MemberModel member in model.Members)
        {
            AppendLine(builder, indent + 1, $"if (string.Equals(name, \"{Escape(member.WireName)}\", global::System.StringComparison.OrdinalIgnoreCase))");
            AppendLine(builder, indent + 1, "{");
            AppendLine(builder, indent + 2, $"result.{member.PropertyName} = {BuildFromStringExpression(member, "value")};");
            AppendLine(builder, indent + 2, "return;");
            AppendLine(builder, indent + 1, "}");
        }

        AppendLine(builder, indent, "}");
    }

    /// <summary>
    /// Builds the expression converting a member value on <paramref name="receiver" /> to its wire string, mirroring
    /// the reflection binders' invariant formatting.
    /// </summary>
    /// <param name="member">The member model.</param>
    /// <param name="receiver">The instance expression.</param>
    /// <returns>The conversion expression text.</returns>
    private static string BuildToStringExpression(MemberModel member, string receiver)
    {
        string access = $"{receiver}.{member.PropertyName}";
        if (member.IsNullable)
            return $"{access}.HasValue ? {FormatValue(member, $"{access}.Value")} : string.Empty";

        if (member.Scalar == ScalarKind.String)
            return $"{access} ?? string.Empty";

        return FormatValue(member, access);
    }

    /// <summary>
    /// Builds the wire-string formatting expression for a non-null value expression.
    /// </summary>
    /// <param name="member">The member model.</param>
    /// <param name="value">The non-null value expression.</param>
    /// <returns>The formatting expression text.</returns>
    private static string FormatValue(MemberModel member, string value) =>
        member.Scalar switch
        {
            ScalarKind.String => value,
            ScalarKind.Boolean => $"{value} ? \"true\" : \"false\"",
            ScalarKind.Char => $"{value}.ToString()",
            ScalarKind.Number => $"{value}.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
            ScalarKind.Guid => $"{value}.ToString()",
            ScalarKind.DateTime => $"{value}.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
            ScalarKind.DateTimeOffset => $"{value}.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
            ScalarKind.TimeSpan => $"{value}.ToString()",
            _ => $"{value}.ToString()",
        };

    /// <summary>
    /// Builds the expression converting a wire string to the member's type, mirroring the reflection binders' invariant
    /// parsing. An empty string maps a nullable member to <see langword="null" />.
    /// </summary>
    /// <param name="member">The member model.</param>
    /// <param name="value">The wire string expression.</param>
    /// <returns>The conversion expression text.</returns>
    private static string BuildFromStringExpression(MemberModel member, string value)
    {
        string parse = member.Scalar switch
        {
            ScalarKind.String => value,
            ScalarKind.Boolean => $"bool.Parse({value})",
            ScalarKind.Char => $"char.Parse({value})",
            ScalarKind.Number => $"{member.TypeDisplay}.Parse({value}, global::System.Globalization.CultureInfo.InvariantCulture)",
            ScalarKind.Guid => $"global::System.Guid.Parse({value})",
            ScalarKind.DateTime => $"global::System.DateTime.Parse({value}, global::System.Globalization.CultureInfo.InvariantCulture, global::System.Globalization.DateTimeStyles.RoundtripKind)",
            ScalarKind.DateTimeOffset => $"global::System.DateTimeOffset.Parse({value}, global::System.Globalization.CultureInfo.InvariantCulture, global::System.Globalization.DateTimeStyles.RoundtripKind)",
            ScalarKind.TimeSpan => $"global::System.TimeSpan.Parse({value}, global::System.Globalization.CultureInfo.InvariantCulture)",
            ScalarKind.Enum => $"({member.TypeDisplay})global::System.Enum.Parse(typeof({member.TypeDisplay}), {value}, true)",
            _ => value,
        };

        return member.IsNullable
            ? $"{value}.Length == 0 ? default({member.TypeDisplay}?) : {parse}"
            : parse;
    }

    /// <summary>
    /// Appends one line at the given indent level.
    /// </summary>
    /// <param name="builder">The output builder.</param>
    /// <param name="indent">The indent level (four spaces per level).</param>
    /// <param name="text">The line text; an empty string emits a blank line.</param>
    private static void AppendLine(StringBuilder builder, int indent, string text)
    {
        if (text.Length == 0)
        {
            builder.AppendLine();
            return;
        }

        for (int i = 0; i < indent; i++)
            builder.Append("    ");

        builder.AppendLine(text);
    }

    /// <summary>
    /// Escapes a wire name for inclusion in a C# string literal.
    /// </summary>
    /// <param name="name">The wire name.</param>
    /// <returns>The escaped text.</returns>
    private static string Escape(string name) =>
        name.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
